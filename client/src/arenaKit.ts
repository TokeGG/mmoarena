/**
 * The shared look of every arena: tiling materials (colour map + normal map, some with a glow map), loaded lazily from the
 * arena packs under /models/arenas, with a plain canvas texture standing in until a pack has arrived (or for good if it
 * cannot be loaded). Arena scenery (arenaMap.ts) asks for materials by name and gets the same stone, sand, ice, wood and
 * basalt on every map; geometry helpers for the cover pieces live here too.
 *
 *   kit.glb       sand, sandbrick, cobble, carved, sandstone, obeliskstone (from the "Arena" scene), snow, ice, frostbrick,
 *                 mossbrick, flagstone, planks, dirt (generated by scripts/prep-arena.mjs)
 *   cinder.glb    the crater (`rim`), horns (`prop_horn_N`), hell textures (lavacrack, basalt, basaltdark, blackbrick, ...)
 *   forge.glb     rock ring (`rim`), lava disc (`lava`), grate disc (`grate`), hell textures
 *   sandstone.glb the stadium shell (`shell_*`), obelisks (`prop_obelisk_N`)
 */

export const KIT_URL = '/models/arenas/kit.glb';
export const arenaPackUrl = (id: string) => `/models/arenas/${id}.glb`;

export function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function canvasTex(w: number, h: number, draw: (g: CanvasRenderingContext2D) => void, repeat?: [number, number]): THREE.CanvasTexture {
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  draw(c.getContext('2d')!);
  const t = new THREE.CanvasTexture(c);
  t.colorSpace = THREE.SRGBColorSpace;
  if (repeat) {
    t.wrapS = t.wrapT = THREE.RepeatWrapping;
    t.repeat.set(repeat[0], repeat[1]);
    t.anisotropy = 4;
  }
  return t;
}

export const shade = (hex: string, k: number) => {
  const n = parseInt(hex.slice(1), 16);
  const f = (v: number) => Math.max(0, Math.min(255, Math.round(v * k)));
  return `rgb(${f((n >> 16) & 255)},${f((n >> 8) & 255)},${f(n & 255)})`;
};

